pub static PRIORITY: Lazy<RwLock<Py>> = Lazy::new(|| RwLock::new(Py::None));
static INIT: Once = Once::new();
thread_local! { static INITIALIZING: Cell<bool> = const { Cell::new(false) }; }
pub fn ensure_init() {
    if INITIALIZING.with(|c| c.get()) { return; }
    INIT.call_once(|| {
        INITIALIZING.with(|c| c.set(true));
        let _ = exc::catch(|| { module_body(); Py::None });
        INITIALIZING.with(|c| c.set(false));
    });
}
pub fn g_PRIORITY() -> Py { ensure_init(); PRIORITY.read().map(|r| r.clone()).unwrap_or(Py::None) }
#[allow(non_snake_case)]
pub fn s_PRIORITY(v: Py) { ensure_init(); if let Ok(mut w) = PRIORITY.write() { *w = v; } }
fn module_body() {
    let _ = py_str("A question about somebody's care is the ward's, not a search (bot/compose/ward.py).\n\n\"How long will she be in hospital\", \"when can she come home\", \"what ward is she on\", \"is he\nallowed visitors\" all reach the composer's search hedge, and no search settles any of them: the\nstay, the discharge, the ward, the theatre list and the results are in that person's notes, and\nthe people holding the notes are the ones looking after them. Each reply says plainly that\nnothing here can see the notes, then names the ward and the one thing to do - ring and ask for\nthe nurse looking after them. Nothing is guessed: no number of days, no ward name, no visiting\nhour. The reading itself is in `bot/compose/ward.py`; this module is only where it is asked from.\n\n`PRIORITY = -985` puts it above the composer's own fallback (-1000) and below every real answer,\nso a knowledge card keeps every line it already answers. It is also above the verdict reader\n(`a_verdict`, -990): a care question beats a question about how to word something.\n");
    s_PRIORITY(neg(&Py::Int(985)));
}
pub fn respond(args: &[Py]) -> Py {
    ensure_init();
    let mut __pos: Vec<Py> = Vec::new();
    let mut __kw: Vec<(String, Py)> = Vec::new();
    for a in args {
        match a {
            Py::Kwargs(kws) => { for (n, v) in kws.iter() { __kw.push((n.clone(), v.clone())); } }
            other => __pos.push(other.clone()),
        }
    }
    let mut text: Py = if __pos.len() > 0 { __pos[0].clone() }
    else if let Some((_, v)) = __kw.iter().find(|(n, _)| n == "text") { v.clone() }
    else { exc::raise(type_err(&format!("missing required argument: text"))) };
    let mut memory: Py = if __pos.len() > 1 { __pos[1].clone() }
    else if let Some((_, v)) = __kw.iter().find(|(n, _)| n == "memory") { v.clone() }
    else { exc::raise(type_err(&format!("missing required argument: memory"))) };
    return crate::gen::compose::ward::answer_for(&[text.clone(), memory.clone()]);
    Py::None
}
pub fn module_obj() -> Py {
    ensure_init();
    Py::Module(Rc::new(PyModule { name: "bot.modules.ward".to_string(),
        get: Rc::new(|attr: &str| match attr {
            "PRIORITY" => Some(g_PRIORITY()),
            "respond" => Some(py_func("respond", |args: &[Py]| respond(args))),
            _ => None,
        }),
        set: None,
    }))
}
